// JobTeardownReconciler consumes teardown events generated by the SlurmPoller
// and orchestrates Kubernetes JobSet deletion, dynamic node deregistration,
// metrics recording, and audit events.
// It implements manager.Runnable and manager.LeaderElectionRunnable.
type JobTeardownReconciler struct {
	client.Client
	ClientMap             *clientmap.ClientMap
	Recorder              record.EventRecorder
	TeardownEvents        <-chan slurmtypes.SlurmJobTeardownEvent
	slurmCallTimeout      time.Duration
	reconciliationTimeout time.Duration
	// onEventHandled is an optional callback invoked after processing an event (used for test synchronization).
	onEventHandled func(ev slurmtypes.SlurmJobTeardownEvent)
}

func (r *JobTeardownReconciler) getSlurmCallTimeout() time.Duration {
	if r.slurmCallTimeout > 0 {
		return r.slurmCallTimeout
	}
	return defaultSlurmCallTimeout
}

func (r *JobTeardownReconciler) getReconciliationTimeout() time.Duration {
	if r.reconciliationTimeout > 0 {
		return r.reconciliationTimeout
	}
	return defaultReconciliationTimeout
}

// NeedLeaderElection implements manager.LeaderElectionRunnable ensuring
// teardown reconciliation only runs on the elected leader.
func (r *JobTeardownReconciler) NeedLeaderElection() bool {
	return true
}

// Start runs the teardown event consumption loop. It implements manager.Runnable.
func (r *JobTeardownReconciler) Start(ctx context.Context) error {
	logger := log.FromContext(ctx).WithName("slurmjob-teardown-reconciler")
	logger.Info("Starting JobTeardownReconciler")

	for {
		select {
		case <-ctx.Done():
			logger.Info("Stopping JobTeardownReconciler")
			return nil
		case ev, ok := <-r.TeardownEvents:
			if !ok {
				logger.Info("TeardownEvents channel closed, stopping JobTeardownReconciler")
				return nil
			}
			if err := r.handleTeardown(ctx, ev); err != nil {
				logger.Error(err, "Failed to handle teardown event", "jobID", ev.JobID, "workloadMixing", ev.WorkloadMixing, "reason", ev.Reason)
			}
			if r.onEventHandled != nil {
				r.onEventHandled(ev)
			}
		}
	}
}

// handleTeardown reconciles a single teardown event.
func (r *JobTeardownReconciler) handleTeardown(ctx context.Context, ev slurmtypes.SlurmJobTeardownEvent) error {
	ctx, cancel := context.WithTimeout(ctx, r.getReconciliationTimeout())
	defer cancel()

	logger := log.FromContext(ctx).WithName("slurmjob-teardown-reconciler")

	jobSetName := fmt.Sprintf("slurm-job-%s", ev.JobID)
	js := &jobsetv1alpha2.JobSet{}
	err := r.Get(ctx, types.NamespacedName{Name: jobSetName, Namespace: ev.WorkloadMixing.Namespace}, js)
	if err != nil {
		if apierrors.IsNotFound(err) {
			logger.V(1).Info("JobSet not found, skipping teardown", "jobSet", jobSetName, "jobID", ev.JobID)
			return nil
		}
		return fmt.Errorf("failed to get JobSet %s/%s: %w", ev.WorkloadMixing.Namespace, jobSetName, err)
	}

	// Fetch parent WorkloadMixing
	wm := &k8sbridgev1alpha1.WorkloadMixing{}
	if err := r.Get(ctx, ev.WorkloadMixing, wm); err != nil {
		if !apierrors.IsNotFound(err) {
			return fmt.Errorf("failed to get parent WorkloadMixing %s: %w", ev.WorkloadMixing, err)
		}
		logger.V(1).Info("Parent WorkloadMixing not found, skipping event and gauge update", "workloadMixing", ev.WorkloadMixing)
		wm = nil
	}

	// Delete dynamic slurmd nodes in Slurm
	if wm != nil && r.ClientMap != nil && wm.Spec.ControllerRef.Name != "" {
		if err := r.cleanupDynamicNodesForWM(ctx, wm, js); err != nil {
			return err
		}
	}

	isDeleting := !js.DeletionTimestamp.IsZero()
	if err := removeJobSetFinalizer(ctx, r.Client, js); err != nil {
		return fmt.Errorf("failed to remove finalizer from JobSet %s/%s: %w", js.Namespace, js.Name, err)
	}

	// Skip duplicate deletion if JobSet is already terminating
	if isDeleting {
		logger.V(1).Info("JobSet already has deletion timestamp, skipping redundant delete", "jobSet", jobSetName, "jobID", ev.JobID)
	} else {
		// Delete JobSet
		if err := r.Delete(ctx, js); err != nil {
			if !apierrors.IsNotFound(err) {
				return fmt.Errorf("failed to delete JobSet %s/%s: %w", js.Namespace, js.Name, err)
			}
		}
		logger.Info("Deleted JobSet for terminated Slurm job", "jobSet", jobSetName, "jobID", ev.JobID, "reason", ev.Reason)
	}

	if !isDeleting && r.Recorder != nil && wm != nil {
		eventReason := "JobTerminated"
		switch ev.Reason {
		case metrics.ReasonJobCompleted:
			eventReason = "JobCompleted"
		case metrics.ReasonJobCancelled:
			eventReason = "JobCancelled"
		case metrics.ReasonJobFailed:
			eventReason = "JobFailed"
		case metrics.ReasonJobOrphaned:
			eventReason = "JobOrphaned"
		}
		r.Recorder.Eventf(wm, corev1.EventTypeNormal, eventReason, "Slurm job %s reached terminal state %s, deleted JobSet %s", ev.JobID, ev.Reason, js.Name)
	}

	partition := ev.Partition
	if partition == "" && js.Labels != nil {
		partition = js.Labels[LabelSlurmPartition]
	}
	if partition == "" && wm != nil && len(wm.Spec.PartitionsMapping) == 1 {
		partition = wm.Spec.PartitionsMapping[0].Partition
	}

	// Record job sync metric
	metrics.RecordJobSync(metrics.StatusSuccess, ev.Reason, ev.WorkloadMixing.Name, partition)

	// Update active jobs gauge
	if wm != nil && partition != "" {
		count, err := CountActiveJobSets(ctx, r.Client, wm, partition, js.Name)
		if err != nil {
			logger.Error(err, "Failed to count active JobSets for gauge metric update", "workloadMixing", wm.Name, "partition", partition)
		} else {
			metrics.SetActiveJobs(wm.Name, partition, count)
		}
	}

	return nil
}

// cleanupDynamicNodesForWM deletes the JobSet's dynamic slurmd nodes using the Slurm client of the
// WorkloadMixing's Slurm Controller. Node cleanup is skipped if the Slurm Controller no longer exists,
// and an error is returned if the Slurm client is not ready yet so the finalizer is retained.
func (r *JobTeardownReconciler) cleanupDynamicNodesForWM(ctx context.Context, wm *k8sbridgev1alpha1.WorkloadMixing, js *jobsetv1alpha2.JobSet) error {
	controllerKey := types.NamespacedName{
		Namespace: wm.Namespace,
		Name:      wm.Spec.ControllerRef.Name,
	}
	slurmClient := r.ClientMap.Get(controllerKey)
	if slurmClient != nil {
		if err := r.cleanupDynamicNodes(ctx, slurmClient, js); err != nil {
			return fmt.Errorf("failed to cleanup dynamic nodes for JobSet %s: %w", js.Name, err)
		}
		return nil
	}
	gone, err := isSlurmControllerGone(ctx, r.Client, controllerKey)
	if err != nil {
		return err
	}
	if !gone {
		return fmt.Errorf("slurm client not found in ClientMap for controller %s", controllerKey)
	}
	log.FromContext(ctx).WithName("slurmjob-teardown-reconciler").Info("Slurm Controller not found, skipping dynamic node cleanup", "controller", controllerKey, "jobSet", js.Name)
	return nil
}

// deriveNodeNames derives dynamic slurmd node names directly from the Kubernetes JobSet
// based on the JobSet pod hostname schema <jobset-name>-slurmd-<jobIndex>-<podIndex>.
// Dynamic slurmd containers register with this deterministic name using -N $(SLURM_NODE_NAME) in both
// standard pod networking and hostNetwork modes.
func deriveNodeNames(js *jobsetv1alpha2.JobSet) []string {
	if js == nil {
		return nil
	}
	var nodeNames []string
	for _, rj := range js.Spec.ReplicatedJobs {
		rjName := rj.Name
		if rjName == "" {
			rjName = ContainerSlurmd
		}
		// In mixed clusters, dynamic worker nodes are slurmd instances.
		// If there are multiple replicated jobs, only derive for slurmd.
		if rjName != ContainerSlurmd && len(js.Spec.ReplicatedJobs) > 1 {
			continue
		}

		parallelism := 1
		if rj.Template.Spec.Parallelism != nil && *rj.Template.Spec.Parallelism > 0 {
			parallelism = int(*rj.Template.Spec.Parallelism)
		}

		for jobIdx := 0; jobIdx < int(rj.Replicas); jobIdx++ {
			for podIdx := 0; podIdx < parallelism; podIdx++ {
				nodeNames = append(nodeNames, fmt.Sprintf("%s-%s-%d-%d", js.Name, rjName, jobIdx, podIdx))
			}
		}
	}
	return nodeNames
}

// cleanupDynamicNodes deletes dynamic slurmd nodes from Slurm.
func (r *JobTeardownReconciler) cleanupDynamicNodes(
	ctx context.Context,
	slurmClient slurmclient.Client,
	js *jobsetv1alpha2.JobSet,
) error {
	return cleanupDynamicNodes(ctx, slurmClient, js, r.getSlurmCallTimeout())
}

// cleanupDynamicNodes deletes dynamic slurmd nodes from Slurm.
func cleanupDynamicNodes(
	ctx context.Context,
	slurmClient slurmclient.Client,
	js *jobsetv1alpha2.JobSet,
	callTimeout time.Duration,
) error {
	if js == nil || slurmClient == nil {
		return nil
	}
	if callTimeout <= 0 {
		callTimeout = defaultSlurmCallTimeout
	}
	logger := log.FromContext(ctx)
	nodeNames := deriveNodeNames(js)

	var errs []error
	var deletedCount int
	for _, nodeName := range nodeNames {
		if err := ctx.Err(); err != nil {
			return fmt.Errorf("context cancelled during dynamic node cleanup: %w", err)
		}

		node := &slurmclienttypes.V0044Node{
			V0044Node: slurmapi.V0044Node{
				Name: ptr.To(nodeName),
			},
		}
		callCtx, cancel := context.WithTimeout(ctx, callTimeout)
		err := slurmClient.Delete(callCtx, node)
		cancel()
		if err == nil {
			deletedCount++
			logger.V(1).Info("Deleted dynamic node from Slurm", "node", nodeName)
		} else if isSlurmNotFound(err) {
			logger.V(1).Info("Dynamic node already removed or not found in Slurm", "node", nodeName)
		} else {
			errs = append(errs, fmt.Errorf("failed to delete dynamic node %s: %w", nodeName, err))
		}
	}
	if deletedCount > 0 {
		logger.Info("Deleted dynamic nodes from Slurm", "jobSet", js.Name, "count", deletedCount)
	}
	return errors.Join(errs...)
}
